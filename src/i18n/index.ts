export function errorKey(error: Failure): Key {
  return (
    {
      NO_DEVICE: 'noDevice',
      DEVICE_LOCKED: 'deviceLocked',
      BUSY: 'busy',
      PERMISSION: 'permission',
      NOT_FOUND: 'notFound',
      OVERWRITE_REQUIRED: 'renameConflict',
      INVALID_PATH: 'invalidPath',
      UNSUPPORTED: 'unsupported',
      IO_ERROR: 'ioError',
    } as const
  )[error.code];
}
